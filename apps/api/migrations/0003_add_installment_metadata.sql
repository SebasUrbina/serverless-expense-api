-- Keep legacy titles intact; installment metadata is independent of the title.
ALTER TABLE transactions ADD COLUMN installment_number INTEGER
  CHECK (installment_number IS NULL OR
    (typeof(installment_number) = 'integer' AND installment_number >= 1));
ALTER TABLE transactions ADD COLUMN installment_total INTEGER
  CHECK (
    (installment_number IS NULL AND installment_total IS NULL) OR
    (installment_number IS NOT NULL AND installment_total IS NOT NULL AND
      typeof(installment_total) = 'integer' AND installment_total >= 2 AND
      installment_number <= installment_total)
  );

-- Only backfill the exact suffix generated by the API, with a nonempty title
-- and a valid pair of positive integers. Malformed or ambiguous titles stay unset.
WITH suffixes AS (
  SELECT id, title, instr(title, ' (Cuota ') AS start,
    substr(title, instr(title, ' (Cuota ') + 8) AS suffix
  FROM transactions
  WHERE instr(title, ' (Cuota ') > 1
), parsed AS (
  SELECT id, title, start,
    CAST(substr(suffix, 1, instr(suffix, '/') - 1) AS INTEGER) AS number,
    CAST(substr(suffix, instr(suffix, '/') + 1) AS INTEGER) AS total
  FROM suffixes
), valid AS (
  SELECT id, number, total FROM parsed
  WHERE number >= 1 AND total >= 2 AND number <= total
    AND trim(substr(title, 1, start - 1)) <> ''
    AND title = substr(title, 1, start - 1) || ' (Cuota ' || number || '/' || total || ')'
)
UPDATE transactions
SET installment_number = (SELECT number FROM valid WHERE valid.id = transactions.id),
    installment_total = (SELECT total FROM valid WHERE valid.id = transactions.id)
WHERE id IN (SELECT id FROM valid);
