import { Bool, OpenAPIRoute } from 'chanfana';
import { z } from 'zod';
import { type AppContext, ErrorResponse, Transaction } from '../types';
import { type SplitInput, splitRows, splitWeights } from '../utils/splits';

const errorContent = { 'application/json': { schema: ErrorResponse } };

function addMonths(baseDate: string, count: number): string {
  const [yearStr, monthStr, dayStr] = baseDate.split('-');
  if (!yearStr || !monthStr || !dayStr) return baseDate;
  const year = Number(yearStr);
  const month = Number(monthStr);
  const day = Number(dayStr);
  let dYear = year;
  let dMonth = month - 1 + count;
  dYear += Math.floor(dMonth / 12);
  dMonth = dMonth % 12;

  const maxDays = new Date(dYear, dMonth + 1, 0).getDate();
  const dDay = Math.min(day, maxDays);

  const finalDate = new Date(dYear, dMonth, dDay);
  const yyyy = finalDate.getFullYear();
  const mm = String(finalDate.getMonth() + 1).padStart(2, '0');
  const dd = String(finalDate.getDate()).padStart(2, '0');
  return `${yyyy}-${mm}-${dd}`;
}

function splitIntoInstallments(amount: number, count: number): number[] {
  const base = Math.floor(amount / count);
  const amounts = Array.from({ length: count }, () => base);
  amounts[0] = amounts[0]! + (amount - base * count);
  return amounts;
}

async function findByClientId(
  db: D1Database,
  userId: string,
  clientId: string,
) {
  const row = await db
    .prepare(
      `SELECT t.*,
         (SELECT json_group_array(tag_id) FROM transaction_tags WHERE transaction_id = t.id) AS tag_json
       FROM transactions t WHERE t.user_id = ? AND t.client_id = ?`,
    )
    .bind(userId, clientId)
    .first<Record<string, unknown> & { tag_json: string | null }>();
  if (!row) return null;
  const { tag_json, ...transaction } = row;
  return { ...transaction, tag_ids: JSON.parse(tag_json ?? '[]') as number[] };
}

export class TransactionCreate extends OpenAPIRoute {
  schema = {
    tags: ['Transactions'],
    summary: 'Create a new Transaction',
    security: [{ BearerAuth: [] }, { ApiKeyAuth: [] }],
    request: {
      body: {
        content: {
          'application/json': {
            schema: Transaction.omit({
              id: true,
              created_at: true,
              installment_number: true,
              installment_total: true,
            }).extend({
              client_id: z.string().min(8).max(64).optional().openapi({
                description:
                  'Unique id generated by the client. Repeating it returns the movement already created instead of a new one.',
              }),
            }),
          },
        },
      },
    },
    responses: {
      '200': {
        description: 'Returns the created transaction',
        content: {
          'application/json': {
            schema: z.object({
              series: z.object({
                success: Bool(),
                result: z.object({
                  transaction: Transaction,
                }),
              }),
            }),
          },
        },
      },
      '400': {
        description:
          'Invalid movement: a shared movement must be an expense with a group_id and at least one split among the group members, and splits need a group_id',
        content: errorContent,
      },
      '403': {
        description: 'Not a member of the group',
        content: errorContent,
      },
      '404': {
        description: 'Category or account not found',
        content: errorContent,
      },
    },
  };

  async handle(c: AppContext) {
    const data = await this.getValidatedData<typeof this.schema>();
    const t = data.body;
    const userId = c.get('userId');
    const db = c.env.DB;
    const clientId = t.client_id ?? null;

    if (clientId) {
      const existing = await findByClientId(db, userId, clientId);
      if (existing) return { success: true, transaction: existing };
    }

    const installmentsCount = t.installments ?? 1;
    if (installmentsCount > 1 && t.type !== 'expense') {
      return c.json(
        {
          success: false,
          error: 'Installments are only supported for expenses',
        },
        400,
      );
    }

    const isShared = t.is_shared ? 1 : 0;
    const groupId = isShared ? t.group_id || null : null;
    const splits = isShared ? (t.splits ?? []) : [];
    const tagIds = t.tag_ids ?? [];

    if ((isShared || t.splits?.length) && !t.group_id) {
      return c.json(
        { success: false, error: 'Shared movements need a group_id' },
        400,
      );
    }
    if (isShared && t.type !== 'expense') {
      return c.json(
        { success: false, error: 'Only expenses can be shared' },
        400,
      );
    }
    if (isShared && splits.length === 0) {
      return c.json(
        {
          success: false,
          error: 'Shared movements need at least one split',
        },
        400,
      );
    }

    const [ownership, members] = await db.batch<
      { id: number } | { user_id: string }
    >([
      db
        .prepare(
          `SELECT
             (SELECT 1 FROM categories WHERE id = ? AND user_id = ?) AS category_ok,
             (SELECT 1 FROM accounts WHERE id = ? AND user_id = ?) AS account_ok`,
        )
        .bind(t.category_id, userId, t.account_id, userId),
      db
        .prepare(`SELECT user_id FROM shared_group_members WHERE group_id = ?`)
        .bind(groupId),
    ]);

    const owned = ownership.results[0] as unknown as {
      category_ok: number | null;
      account_ok: number | null;
    };
    if (!owned?.category_ok || !owned?.account_ok) {
      return c.json(
        { success: false, error: 'Category or account not found' },
        404,
      );
    }

    if (isShared) {
      const memberIds = new Set(
        (members.results as { user_id: string }[]).map((m) => m.user_id),
      );
      if (!memberIds.has(userId)) {
        return c.json(
          { success: false, error: 'You are not a member of this group' },
          403,
        );
      }
      if (splits.some((s) => !memberIds.has(s.user_id))) {
        return c.json(
          { success: false, error: 'Split users must be members of the group' },
          400,
        );
      }
    }

    let weights: number[] = [];
    if (splits.length > 0) {
      const resolved = splitWeights(t.amount, splits as SplitInput[]);
      if ('error' in resolved) {
        return c.json({ success: false, error: resolved.error }, 400);
      }
      weights = resolved.weights;
    }
    const splitUserIds = splits.map((s) => s.user_id);

    // D1 runs a batch as a single serialized transaction, so MAX(id) is the row inserted just before.
    const lastTransactionId = `(SELECT MAX(id) FROM transactions)`;
    const amounts = splitIntoInstallments(t.amount, installmentsCount);
    const isInstallment = installmentsCount > 1;
    const statements: D1PreparedStatement[] = [];
    const insertIndexes: number[] = [];

    amounts.forEach((amount, idx) => {
      insertIndexes.push(statements.length);
      statements.push(
        db
          .prepare(
            `INSERT INTO transactions (title, amount, category_id, type, account_id, user_id, date, is_shared, group_id, installment_number, installment_total, client_id)
             VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) RETURNING *`,
          )
          .bind(
            t.title,
            amount,
            t.category_id,
            t.type,
            t.account_id,
            userId,
            addMonths(t.date, idx),
            isShared,
            groupId,
            isInstallment ? idx + 1 : null,
            isInstallment ? installmentsCount : null,
            idx === 0 ? clientId : null,
          ),
      );

      if (tagIds.length > 0) {
        statements.push(
          db
            .prepare(
              `INSERT INTO transaction_tags (transaction_id, tag_id)
               SELECT ${lastTransactionId}, id FROM tags
               WHERE user_id = ? AND id IN (SELECT value FROM json_each(?))`,
            )
            .bind(userId, JSON.stringify(tagIds)),
        );
      }

      for (const split of splitRows(amount, splitUserIds, weights)) {
        statements.push(
          db
            .prepare(
              `INSERT INTO transaction_splits (transaction_id, user_id, amount, percentage)
               VALUES (${lastTransactionId}, ?, ?, ?)`,
            )
            .bind(split.user_id, split.amount, split.percentage),
        );
      }
    });

    let results: D1Result<Record<string, unknown>>[];
    try {
      results = await db.batch<Record<string, unknown>>(statements);
    } catch (error) {
      // A concurrent request with the same client_id won the unique index.
      const existing = clientId && (await findByClientId(db, userId, clientId));
      if (existing) return { success: true, transaction: existing };
      throw error;
    }
    const first = results[insertIndexes[0]!]!.results[0] as {
      id: number;
    } & Record<string, unknown>;

    let finalSplits: unknown[] = [];
    if (splits.length > 0) {
      const splitsResult = await db
        .prepare(
          `SELECT ts.*, sgm.nickname
           FROM transaction_splits ts
           LEFT JOIN shared_group_members sgm ON sgm.user_id = ts.user_id AND sgm.group_id = ?
           WHERE ts.transaction_id = ?`,
        )
        .bind(groupId, first.id)
        .all();
      finalSplits = splitsResult.results;
    }

    return {
      success: true,
      transaction: {
        ...first,
        tag_ids: tagIds,
        splits: finalSplits,
      },
    };
  }
}
